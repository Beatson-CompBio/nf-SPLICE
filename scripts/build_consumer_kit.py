"""Refresh the generated parts of bundle-consumer-kit/ from their sources.

python scripts/build_consumer_kit.py          # write
python scripts/build_consumer_kit.py --check  # fail if the kit is stale

The kit is for developers who build on SPLICE bundles without installing
nf-splice, so it carries its own copies of:

- the formal contract definitions and examples (from ``docs/schemas/``);
- a complete example bundle, built by nf-splice's real services from the
  multi-route test fixture (alternative aligners, an optional step, job and
  sample outputs);
- an ``analysis_output.json`` generated by nf-splice for one completed job of
  that bundle (the STAR route only, so other routes' outputs are absent).

The written skills and AGENTS.md are maintained by hand; the drift tests in
``tests/test_consumer_kit.py`` check them against these files.
"""

from __future__ import annotations

import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "bundle-consumer-kit"
FAMILIES = ("bundle", "inputs", "outputs", "components", "execution-profiles")
JOB = {
    "job_id_short": "A123",
    "job_id_long": "3f2c8a3e-6b1d-4c4e-9a52-1f0d2b7c9e10",
    "config_profile": "profile-local-6c6f63616c",
    "execution_timestamp": "2026-10-15T09:30:00Z",
    "job_metadata": {
        "engine": "nextflow",
        "engine_execution_id": "7e1d9c2b-5a4f-4e3b-8c6d-0a1b2c3d4e5f",
        "nextflow": {
            "session_id": "7e1d9c2b-5a4f-4e3b-8c6d-0a1b2c3d4e5f",
            "run_name": "happy_turing",
        },
    },
}
#: Stands in for the machine-specific path of the example job's results.
PUBLISH_DIRECTORY = "/data/jobs/A123/results"


def _contract_files() -> dict[str, bytes]:
    found = {}
    for family in FAMILIES:
        for source in sorted((ROOT / "docs" / "schemas" / family).glob("v*/*.json")):
            relative = source.relative_to(ROOT / "docs" / "schemas")
            found[f"schemas/{relative.as_posix()}"] = source.read_bytes()
    return found


def _example_files() -> dict[str, bytes]:
    sys.path.insert(0, str(ROOT / "tests"))
    found: dict[str, bytes] = {}
    with tempfile.TemporaryDirectory(prefix="nf-splice-kit-") as folder:
        # The example is not a Git repository. Without a ceiling, a temporary
        # folder inside a clone would let Git report the clone's own commit as
        # the example's revision, so the output would depend on the machine.
        previous = os.environ.get("GIT_CEILING_DIRECTORIES")
        os.environ["GIT_CEILING_DIRECTORIES"] = folder
        try:
            found |= _build_example(Path(folder))
        finally:
            if previous is None:
                os.environ.pop("GIT_CEILING_DIRECTORIES", None)
            else:
                os.environ["GIT_CEILING_DIRECTORIES"] = previous
    return found


def _build_example(folder: Path) -> dict[str, bytes]:
    from multi_route import EXAMPLE, author_all, build, copy_fixture
    from nf_splice.runtime.analysis_output import (
        generate_analysis_output,
        load_and_validate_analysis_output,
    )

    found: dict[str, bytes] = {}
    root = copy_fixture(folder)
    author_all(root)
    build(root)
    bundle = root / "splice"
    for path in sorted(bundle.rglob("*")):
        if path.is_file():
            key = f"examples/bundle/{path.relative_to(bundle).as_posix()}"
            found[key] = path.read_bytes()
    result = generate_analysis_output(
        root,
        publish_directory=EXAMPLE,
        job_metadata=JOB,
        checksum_algorithm="sha256",
    )
    document = dict(result.document)
    document["publish_directory"] = PUBLISH_DIRECTORY
    content = (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode()
    written = folder / "analysis_output.json"
    written.write_bytes(content)
    report = load_and_validate_analysis_output(root, written)
    assert report.valid, report
    found["examples/analysis_output.json"] = content
    return found


def expected() -> dict[str, bytes]:
    return _contract_files() | _example_files()


def _generated_paths() -> set[str]:
    return {
        path.relative_to(KIT).as_posix()
        for folder in ("schemas", "examples")
        for path in (KIT / folder).rglob("*")
        if path.is_file()
    }


def main(argv: list[str]) -> int:
    wanted = expected()
    present = _generated_paths() if KIT.exists() else set()
    if "--check" in argv:
        stale = sorted(
            name
            for name, data in wanted.items()
            if not (KIT / name).is_file() or (KIT / name).read_bytes() != data
        )
        extra = sorted(present - set(wanted))
        if stale or extra:
            for name in stale:
                print(f"stale: bundle-consumer-kit/{name}", file=sys.stderr)
            for name in extra:
                print(f"not generated: bundle-consumer-kit/{name}", file=sys.stderr)
            print("run: python scripts/build_consumer_kit.py", file=sys.stderr)
            return 1
        return 0
    for folder in ("schemas", "examples"):
        shutil.rmtree(KIT / folder, ignore_errors=True)
    for name, data in wanted.items():
        target = KIT / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print(f"wrote {len(wanted)} files below bundle-consumer-kit/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
