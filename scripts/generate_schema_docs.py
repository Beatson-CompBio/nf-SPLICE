"""Generate docs/schemas/<family>/README.md field dictionaries.

python scripts/generate_schema_docs.py          # write
python scripts/generate_schema_docs.py --check  # fail if stale/undocumented
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml  # type: ignore[import-untyped]

from nf_splice.contracts import families, meta_schema, release

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs" / "schemas"


def _resolve(schema: dict[str, Any], root: dict[str, Any]) -> dict[str, Any]:
    if "$ref" in schema:
        return dict(root["$defs"][schema["$ref"].rsplit("/", 1)[-1]])
    return schema


def _type(schema: dict[str, Any]) -> str:
    if "const" in schema:
        return f"const `{json.dumps(schema['const'])}`"
    if "enum" in schema:
        return "enum " + ", ".join(f"`{item}`" for item in schema["enum"])
    kind = schema.get("type", "any")
    if schema is False:
        return "forbidden"
    return kind if isinstance(kind, str) else " or ".join(kind)


def _constraints(schema: dict[str, Any]) -> str:
    parts = []
    keys = ("pattern", "format", "minLength", "minimum", "minItems", "minProperties")
    for key in keys:
        if key in schema:
            parts.append(f"{key}: `{schema[key]}`")
    if schema.get("uniqueItems"):
        parts.append("unique items")
    if schema.get("additionalProperties") is False:
        parts.append("closed object")
    return "; ".join(parts)


Row = tuple[str, dict[str, Any], bool]


def rows(schema: dict[str, Any], root: dict[str, Any], prefix: str = "") -> list[Row]:
    found = []
    schema = _resolve(schema, root)
    required = set(schema.get("required", []))
    for name, child in (schema.get("properties") or {}).items():
        path = f"{prefix}.{name}" if prefix else name
        if child is False:
            found.append((path, {"type": "forbidden"}, False))
            continue
        target = _resolve(child, root)
        found.append((path, target, name in required))
        if target.get("type") == "array" and isinstance(target.get("items"), dict):
            found.extend(rows(target["items"], root, f"{path}[]"))
        elif isinstance(target.get("additionalProperties"), dict):
            found.extend(rows(target["additionalProperties"], root, f"{path}.*"))
        else:
            found.extend(rows(target, root, path))
    return found


def _note(notes: dict[str, Any], key: str, path: str) -> dict[str, str] | None:
    family = notes.get(key, {})
    for candidate in (path, "*." + path.split(".*.", 1)[-1] if ".*." in path else None):
        if candidate and candidate in family:
            return dict(family[candidate])
    generic = path.split("properties.*.", 1)[-1] if "properties.*." in path else None
    if generic and f"*.{generic}" in family:
        return dict(family[f"*.{generic}"])
    return dict(notes["common"][path]) if path in notes["common"] else None


def render(key: str, notes: dict[str, Any]) -> tuple[str, list[str]]:
    item = next(value for value in families() if value.key == key)
    schema = meta_schema(item.id)
    version = dict(release().contracts)[item.id]
    missing = []
    lines = [
        f"# `{item.path}` field reference",
        "",
        f"Family `{item.id}`, revision `{version}` ({item.title}). Formal definition:",
        f"[`v{version}/schema.json`](v{version}/schema.json); example:",
        f"[`v{version}/example.json`](v{version}/example.json). Generated by",
        "`scripts/generate_schema_docs.py` from the packaged definition and",
        "`docs/schemas/fields.yaml`; do not edit by hand.",
        "",
        "| JSON path | Type | Required | Constraints | Meaning | Consumer use "
        "| Privacy |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for path, child, required in rows(schema, schema):
        note = _note(notes, key, path)
        if note is None:
            missing.append(path)
            note = {}
        lines.append(
            f"| `{path}` | {_type(child)} | {'yes' if required else 'no'} | "
            f"{_constraints(child)} | {note.get('meaning', '')} | "
            f"{note.get('use', '')} | {note.get('privacy', 'public')} |"
        )
    lines += [
        "",
        "Unknown keys are rejected wherever the definition is a closed object.",
        "Compatibility rules and the release mapping are in `docs/CONTRACTS.md`.",
        "",
    ]
    return "\n".join(lines), missing


def main(argv: list[str]) -> int:
    notes = yaml.safe_load((DOCS / "fields.yaml").read_text(encoding="utf-8"))
    check = "--check" in argv
    problems = []
    for item in families():
        text, missing = render(item.key, notes)
        problems.extend(f"{item.key}: undocumented {path}" for path in missing)
        target = DOCS / item.key / "README.md"
        if check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                problems.append(f"{target.relative_to(ROOT)} is stale")
        else:
            target.write_text(text, encoding="utf-8")
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
