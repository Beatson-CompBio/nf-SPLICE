"""Render the 0.3.0 ``bundle.json`` index, bundle README and lock."""

from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

from nf_splice import __version__
from nf_splice.contracts import (
    BUNDLE_FAMILY,
    data_document_header,
    families,
    release,
)
from nf_splice.domain.identity import Maintainer, PipelineMetadata

LOCK_FORMAT_VERSION = "2.0"
BUNDLE_FILES = {
    "inputs_schema": "inputs.schema.json",
    "outputs_catalogue": "outputs.yaml",
    "outputs_schema": "outputs.schema.json",
    "ro_crate": "ro-crate-metadata.json",
    "components": "components.json",
    "execution_profiles": "execution-profiles.json",
}
_PURPOSE = {
    "bundle.json": "Bundle index: identity, contract revisions, file index.",
    "inputs.schema.json": "Workflow input contract (JSON Schema 2020-12).",
    "outputs.yaml": "Developer-readable output catalogue.",
    "outputs.schema.json": "Job analysis_output.json schema and x-output-catalog.",
    "components.json": "Components, container sources and image distributions.",
    "execution-profiles.json": "Reviewed execution profiles and the default profile.",
    "ro-crate-metadata.json": "Reviewed workflow RO-Crate.",
    "README.md": "This description.",
    "nf-splice.lock.json": "Generator, source and managed-file hashes.",
}


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _json(document: Any) -> bytes:
    return (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


@dataclass(frozen=True, slots=True)
class RenderedBundleIndex:
    """Byte-stable whole-bundle metadata."""

    bundle: bytes
    readme: bytes
    lock: bytes


def bundle_document(
    metadata: PipelineMetadata,
    maintainers: tuple[Maintainer, ...],
    default_profile: str | None,
) -> dict[str, Any]:
    """Return the ordered bundle index document."""
    mapping = dict(release().contracts)
    document: dict[str, Any] = {
        "bundle_format": "splice-pipeline-bundle",
        **data_document_header(BUNDLE_FAMILY),
        "pipeline": metadata.ordered_document(),
    }
    if metadata.assay_capabilities:
        from nf_splice.catalogue import default_catalogue

        document["assay_vocabulary"] = default_catalogue().provenance.reference()
    if maintainers:
        document["maintainers"] = [
            item.model_dump(mode="json", exclude_none=True) for item in maintainers
        ]
    document["schemas"] = {
        item.id: {"version": mapping[item.id], "path": item.path} for item in families()
    }
    document["files"] = dict(BUNDLE_FILES)
    if default_profile is not None:
        document["default_execution_profile"] = default_profile
    return document


def _readme(metadata: PipelineMetadata, generated: Mapping[str, bytes]) -> bytes:
    mapping = dict(release().contracts)
    contract_rows = "\n".join(
        f"| `{item.path}` | `{item.id}` | {mapping[item.id]} |" for item in families()
    )
    paths = sorted({*generated, "bundle.json", "README.md", "nf-splice.lock.json"})
    file_rows = "\n".join(
        f"| `{path}` | {_PURPOSE.get(path, 'Reviewed execution configuration.')} |"
        for path in paths
    )
    title = metadata.title or metadata.name
    description = f"\n{metadata.description}\n" if metadata.description else ""
    text = (
        f"# {title} SPLICE workflow bundle\n{description}\n"
        f"Workflow `{metadata.id}` version `{metadata.version}` "
        f"({metadata.repository_url}). Generated by nf-splice {__version__}.\n\n"
        "## Contract revisions\n\n"
        "| File | Contract family | Revision |\n| --- | --- | --- |\n"
        f"{contract_rows}\n\n"
        "## Contents\n\n| File | Purpose |\n| --- | --- |\n"
        f"{file_rows}\n\n"
        "## Ownership and editing\n\n"
        "The editable authoring sources are private draft files kept in the "
        "repository's ignored `.splice-local/` folder; edit them through "
        "nf-splice, then validate and promote. Files in this directory are "
        "published artefacts: do not edit them by hand. The "
        "repository-root RO-Crate and adopted source configs remain "
        "developer-owned.\n\n"
        "Each completed workflow job produces its own `analysis_output.json` in "
        "the job's output directory; it is never part of this static bundle.\n"
    )
    return text.encode("utf-8")


def render_bundle_index(
    metadata: PipelineMetadata,
    maintainers: tuple[Maintainer, ...],
    default_profile: str | None,
    *,
    generated_files: Mapping[str, bytes],
    sources: Mapping[str, Mapping[str, str]],
    provenance: Mapping[str, Any],
    repository_revision: str | None,
) -> RenderedBundleIndex:
    """Render bundle.json, README.md and the lock around layer payloads."""
    bundle = _json(bundle_document(metadata, maintainers, default_profile))
    readme = _readme(metadata, generated_files)
    managed = {**generated_files, "bundle.json": bundle, "README.md": readme}
    lock = {
        "schema_version": LOCK_FORMAT_VERSION,
        "generator": {"name": "nf-splice", "version": __version__},
        "repository": {"url": metadata.repository_url, "revision": repository_revision},
        "contracts": dict(sorted(release().contracts)),
        "sources": {path: dict(sources[path]) for path in sorted(sources)},
        "provenance": dict(provenance),
        "managed_files": {
            path: {"sha256": _sha256(payload)}
            for path, payload in sorted(managed.items())
        },
    }
    return RenderedBundleIndex(bundle=bundle, readme=readme, lock=_json(lock))
